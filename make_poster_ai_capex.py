def pc(x, d=0) -> str:
    if x is None or pd.isna(x):
        return "—"
    c = "rd" if x > 0 else "gn" if x < 0 else ""
    return f'<span class="{c}">{x * 100:+.{d}f}%</span>'


def pe(x) -> str:
    return "—" if pd.isna(x) else (f"{x:.0f}" if x < 200 else "&gt;200")


