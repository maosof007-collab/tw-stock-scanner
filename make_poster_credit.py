def pc(x, d=1) -> str:
    if x is None or pd.isna(x):
        return "—"
    c = "rd" if x > 0 else "gn" if x < 0 else ""
    return f'<span class="{c}">{x:+.{d}f}%</span>'


def table(heads: list, rows: list) -> str:
    return ("<table><tr>" + "".join(f"<th>{h}</th>" for h in heads) + "</tr>"
            + "".join("<tr>" + "".join(c if c.startswith("<td") else f'<td class="n">{c}</td>' for c in r) + "</tr>" for r in rows) + "</table>")


def chart(d: pd.DataFrame, tight: pd.DataFrame) -> str:
    """上:加權指數(對數);下:放款年增 − 存款年增(點)。橘色底 = 吃緊的期間。"""
    d = d[(d.index >= "1988-01") & d.px.notna()]
    W, H, L, R, T1, B1, T2, B2 = 900, 430, 46, 12, 14, 250, 276, 400
    n = len(d)
    X = lambda i: L + (W - L - R) * i / (n - 1)
    lp = np.log(d.px.values.astype(float))
    y1 = lambda v: B1 - (v - lp.min()) / (lp.max() - lp.min()) * (B1 - T1)
    g = d.gap.clip(-12, 22)
    y2 = lambda v: B2 - (v + 12) / 34 * (B2 - T2)
    pos = {p: i for i, p in enumerate(d.index)}
    o = [f'<svg class="ch" viewBox="0 0 {W} {H}" xmlns="http://www.w3.org/2000/svg" font-family="Arial,sans-serif">']
    for _, r in tight.iterrows():
        a = pos.get(pd.Period(r["開始"], "M"))
        b = n - 1 if r["結束"] == "還在" else pos.get(pd.Period(r["結束"], "M"))
        if a is None or b is None:
            continue
        o.append(f'<rect x="{X(a):.1f}" y="{T1}" width="{max(X(b) - X(a), 3):.1f}" height="{B2 - T1}" fill="{TIGHT_C}" opacity="0.2"/>')
        o.append(f'<text x="{X(a) + 2:.1f}" y="{T1 + 10}" font-size="10" fill="#a8581d">{r["開始"][:4]}</text>')
    for v in (3000, 6000, 12000, 24000, 48000):
        if lp.min() <= np.log(v) <= lp.max():
            o.append(f'<line x1="{L}" x2="{W - R}" y1="{y1(np.log(v)):.1f}" y2="{y1(np.log(v)):.1f}" stroke="#e3e7ec"/>'
                     f'<text x="{L - 5}" y="{y1(np.log(v)) + 3.5:.1f}" font-size="10" fill="#5b6673" text-anchor="end">{v:,}</text>')
    for v in (-10, 0, 10, 20):
        o.append(f'<line x1="{L}" x2="{W - R}" y1="{y2(v):.1f}" y2="{y2(v):.1f}" stroke="{"#9aa4af" if v == 0 else "#e3e7ec"}"/>'
                 f'<text x="{L - 5}" y="{y2(v) + 3.5:.1f}" font-size="10" fill="#5b6673" text-anchor="end">{v:+d}</text>'.replace(">+0<", ">0<"))
    o.append(f'<line x1="{L}" x2="{W - R}" y1="{y2(C.GAP):.1f}" y2="{y2(C.GAP):.1f}" stroke="{TIGHT_C}" stroke-dasharray="4 3"/>')
    o.append(f'<text x="{W - R}" y="{y2(C.GAP) - 4:.1f}" font-size="10" fill="#a8581d" text-anchor="end">吃緊門檻 +{C.GAP:.0f} 點</text>')
    o.append(f'<polyline fill="none" stroke="{LINE_C}" stroke-width="1.6" points="' + " ".join(f"{X(i):.1f},{y1(v):.1f}" for i, v in enumerate(lp)) + '"/>')
    pts = [(X(pos[p]), y2(v)) for p, v in g.items() if pd.notna(v)]
    o.append(f'<polyline fill="none" stroke="{GAP_C}" stroke-width="1.6" points="' + " ".join(f"{x:.1f},{y:.1f}" for x, y in pts) + '"/>')
    for yr in range(1990, 2030, 5):
        i = pos.get(pd.Period(f"{yr}-01", "M"))
        if i is not None:
            o.append(f'<text x="{X(i):.1f}" y="{H - 14}" font-size="10" fill="#5b6673" text-anchor="middle">{yr}</text>')
    o.append(f'<text x="{L + 4}" y="{B1 - 6}" font-size="11" fill="{LINE_C}">加權指數(對數刻度)</text>')
    o.append(f'<text x="{L + 4}" y="{T2 + 4}" font-size="11" fill="{GAP_C}">放款年增率 − 存款年增率(點)</text>')
    o.append("</svg>")
    return "".join(o)


