R = it.readings(tuple(c for c in codes if c in known), with_health=True)


def table(rows) -> str:
    out = '<table><tr><th>公司</th><th>衛星占營收</th><th>近3月營收</th><th>籌碼</th></tr>'
    for code, name, role, share, flag in rows:
        if code in R.index and pd.notna(R.loc[code, "yoy3"]):
            x = R.loc[code]
            rev = f'{ud(round(float(x.yoy3)), f"{float(x.yoy3):+.0f}%")}<br><small>前3月 {float(x.yoy3_prev):+.0f}%</small>'
            bh = "" if pd.isna(x.bh4) else f'大戶 {ud(round(float(x.bh4), 1), f"{float(x.bh4):+.1f}pp")}'
            hi = "上市未滿一年" if pd.isna(x.off_hi) else f"距高 {float(x.off_hi):.0f}%"
            chip = f'{hi}<br><small>{bh} {x.health}</small>'
        else:
            rev, chip = "—", "<small>系統無資料</small>"
        mark = "●" if flag == "✓" else "?"
        out += (f'<tr><td><b>{name}</b> {code}<br><small>{role}</small></td>'
                f'<td>{mark} {share}</td><td class="n">{rev}</td><td>{chip}</td></tr>')
    return out + "</table>"


