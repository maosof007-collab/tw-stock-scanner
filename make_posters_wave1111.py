D = "2026/11/11"
REV = pd.read_csv("data/bulk_fin/rev_all.csv.gz", dtype={"code": str})


def fc_table(code, yoys, note):
    """11/12 月三情境營收預估表(去年同月×(1+YoY));yoys=(保守,中性,樂觀)%"""
    rows = []
    for ym in ("11", "12"):
        prev = REV[(REV["code"] == code) & (REV["ym"] == f"2025-{ym}")]["revenue"]
        if not len(prev):
            continue
        b = float(prev.iloc[0]) / 100
        c_, m_, o_ = (b * (1 + y / 100) for y in yoys)
        rows.append(f'<tr><td><b>2026/{ym}</b></td><td class="n">{b:.2f} 億</td>'
                    f'<td class="n">{c_:.2f}</td><td class="n yl"><b>{m_:.2f}</b></td>'
                    f'<td class="n rd">{o_:.2f}</td></tr>')
    return (f'<table><tr><th>月份</th><th>去年同月</th><th>保守 {yoys[0]:+g}%</th>'
            f'<th>中性 {yoys[1]:+g}%</th><th>樂觀 {yoys[2]:+g}%</th></tr>{"".join(rows)}</table>'
            f'<div class="note">{note}</div>')


def scn_table(px, rows, note):
    """情境估值表 rows=[(標,EPS,PE,推估價,漲跌%)]"""
    tr = ""
    for i, (nm, eps, pe, tgt) in enumerate(rows):
        chg = (tgt / px - 1) * 100
        bg = ['style="background:#eaf3ff"', 'class="yl"', 'style="background:#fff3e8"'][i]
        tr += (f'<tr><td {bg}><b>{nm}</b></td><td class="n">{eps}</td><td class="n">{pe} 倍</td>'
               f'<td class="n">{tgt:g} 元 {ud(round(chg), f"{chg:+.0f}%")}</td></tr>')
    return (f'<table><tr><th>情境</th><th>年化 EPS</th><th>本益比</th><th>推估股價 vs {px:g}</th></tr>'
            + tr + f'</table><div class="note">{note}</div>')


def build(code, name, title_b, subtitle, brand, cols, src_note):
    html = shell(title_html=f"{name}<b>({code})</b>{title_b}", subtitle=subtitle,
                 brand=brand, cols=cols,
                 footer=f"素材:{src_note} · {D} · 本海報為研究筆記非投資建議")
    print("saved:", save_poster(code, "20261111", html))


